      END
      SUBROUTINE SEG(X1,Y1,X2,Y2,U)
      CALL LINE(NINT(X1*U),NINT(Y1*U),NINT(X2*U),NINT(Y2*U))
      RETURN
      END
      SUBROUTINE WALL(X1,Y1,X2,Y2,SX,SY,HP,HDX,HDY,U)
      CALL SEG(X1,Y1,X2,Y2,U)
      D=SQRT((X2-X1)**2+(Y2-Y1)**2)
      N=INT(D/HP)
      DO 10 I=0,N
      T=I*HP/D
      XA=X1+T*(X2-X1)
      YA=Y1+T*(Y2-Y1)
      IF(SY.NE.0.) CALL SEG(XA,YA,XA-SY*HDX,YA+SY*HDY,U)
      IF(SX.NE.0.) CALL SEG(XA,YA,XA+SX*HDX,YA+HDY,U)
  10  CONTINUE
      RETURN
      END
      SUBROUTINE ARROW(X1,Y1,X2,Y2,AL,AW,U)
      INTEGER NX(3),NY(3)
      D=SQRT((X2-X1)**2+(Y2-Y1)**2)
      EX=(X2-X1)/D
      EY=(Y2-Y1)/D
      CALL SEG(X1,Y1,X2-EX*AL*0.5,Y2-EY*AL*0.5,U)
      NX(1)=NINT(X2*U)
      NY(1)=NINT(Y2*U)
      NX(2)=NINT((X2-EX*AL-EY*AW)*U)
      NY(2)=NINT((Y2-EY*AL+EX*AW)*U)
      NX(3)=NINT((X2-EX*AL+EY*AW)*U)
      NY(3)=NINT((Y2-EY*AL-EX*AW)*U)
      CALL SHDPAT(16)
      CALL AREAF(NX,NY,3)
      CALL SHDPAT(0)
      RETURN
      END
