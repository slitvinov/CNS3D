      SUBROUTINE INSET(HIN,CWI,WIN,HP,HDX,HDY,AL,AW,U)
      CALL LINWID(NINT(WIN*U))
      CALL WALL(555.,177.,1204.,177.,0.,-1.,HP,HDX,HDY,U)
      CALL WALL(557.,282.,688.,282.,0.,-1.,HP,HDX,HDY,U)
      CALL WALL(688.,282.,688.,335.,-1.,0.,HP,HDX,HDY,U)
      CALL WALL(688.,335.,1204.,335.,0.,1.,HP,HDX,HDY,U)
      CALL SEG(509.,335.,664.,335.,U)
      CALL SEG(554.5,356.,554.5,405.,U)
      CALL SEG(687.5,340.,687.5,409.,U)
      CALL ARROW(525.,337.,525.,272.,AL,AW,U)
      CALL ARROW(609.,216.,609.,177.,AL,AW,U)
      CALL ARROW(609.,246.,609.,282.,AL,AW,U)
      CALL ARROW(608.5,363.,608.5,336.,AL,AW,U)
      CALL ARROW(598.,382.5,555.,382.5,AL,AW,U)
      CALL ARROW(642.,382.5,687.,382.5,AL,AW,U)
